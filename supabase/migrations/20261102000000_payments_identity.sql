-- Payments hardening + identity linking (Agent 1).
-- Run after 20260605000000_premium_payments.sql. All tables stay service-role only (RLS on, no policies).

-- 1. Identity links: one person, many logins (Clerk on web, Firebase on mobile).
create table if not exists public.user_identities (
  id bigint generated by default as identity primary key,
  clerk_id text unique,
  firebase_uid text unique,
  email text not null,
  email_verified boolean not null default true,
  linked_via text not null default 'verified_email',
  created_at timestamptz not null default now(),
  check (clerk_id is not null and firebase_uid is not null)
);
create index if not exists user_identities_email_idx on public.user_identities (lower(email));
alter table public.user_identities enable row level security;

-- 2. Payment transactions: normalise status vocabulary and add receipt fields.
alter table public.payment_transactions
  add column if not exists order_id text,
  add column if not exists payment_id text,
  add column if not exists email text,
  add column if not exists currency text not null default 'INR',
  add column if not exists amount_paise integer,
  add column if not exists base_amount_paise integer,
  add column if not exists gst_rate_percent numeric(5,2) not null default 0,
  add column if not exists gst_amount_paise integer not null default 0,
  add column if not exists receipt_no text,
  add column if not exists source text not null default 'web',
  add column if not exists failure_reason text,
  add column if not exists paid_at timestamptz,
  add column if not exists refunded_at timestamptz,
  add column if not exists receipt_emailed_at timestamptz;

update public.payment_transactions set order_id = txnid where order_id is null;
update public.payment_transactions set status = 'created' where status = 'order_created';
update public.payment_transactions set status = 'paid' where status = 'premium_activated';
update public.payment_transactions set payment_id = provider_reference_id
  where status = 'paid' and payment_id is null and provider_reference_id like 'pay_%';

create unique index if not exists payment_transactions_order_id_key on public.payment_transactions (order_id);
-- Idempotency: one payment id can only ever belong to one row.
create unique index if not exists payment_transactions_payment_id_key on public.payment_transactions (payment_id) where payment_id is not null;
create unique index if not exists payment_transactions_receipt_no_key on public.payment_transactions (receipt_no) where receipt_no is not null;
create index if not exists payment_transactions_user_idx on public.payment_transactions (user_id, created_at desc);

-- 3. Append-only log of every state transition and webhook delivery.
create table if not exists public.payment_events (
  id bigint generated by default as identity primary key,
  event_id text unique,              -- Razorpay x-razorpay-event-id; makes webhook replays harmless
  order_id text,
  payment_id text,
  user_id text,
  kind text not null,                -- e.g. order_created, verify, webhook:payment.captured, entitlement_granted
  from_status text,
  to_status text,
  detail jsonb,
  created_at timestamptz not null default now()
);
create index if not exists payment_events_order_idx on public.payment_events (order_id);
alter table public.payment_events enable row level security;

-- 4. When Lifetime access started (updated_at moves on every upsert, so it cannot answer this).
alter table public.premium_members add column if not exists premium_since timestamptz;
update public.premium_members set premium_since = updated_at where premium_since is null;
