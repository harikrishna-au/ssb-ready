#!/usr/bin/env node
/* eslint-disable no-console */
/**
 * Shows every endpoint the backend exposes, and whether each one is live.
 *
 *   node scripts/api_status.js                          list all routes (access level, group)
 *   node scripts/api_status.js --md                     also write docs/API.md
 *   node scripts/api_status.js --probe http://localhost:5001      probe a running server
 *   node scripts/api_status.js --probe https://your-backend.onrender.com
 *
 * Probing is safe: it sends NO login and NO body. Login-protected routes answer 401 before any handler
 * runs, so nothing is created or changed. Public POST/PUT/DELETE routes are listed but never called.
 */
const fs = require('fs');
const path = require('path');

process.env.LOG_SILENT = process.env.LOG_SILENT || '1';
process.env.SUPABASE_URL = process.env.SUPABASE_URL || 'https://example.invalid';
process.env.SUPABASE_KEY = process.env.SUPABASE_KEY || 'x';
const { loadEnv } = require('../config');
loadEnv();
const { createApp } = require('../app');

const args = process.argv.slice(2);
const probeIdx = args.indexOf('--probe');
const base = probeIdx >= 0 ? String(args[probeIdx + 1] || '').replace(/\/+$/, '') : null;

function walk(stack, prefix = '') {
  const out = [];
  for (const layer of stack) {
    if (layer.route) {
      const guarded = layer.route.stack.some((l) => l.handle && l.handle.isGuard);
      const methods = Object.keys(layer.route.methods).map((m) => (m === '_all' ? 'ALL' : m.toUpperCase()));
      for (const method of methods) out.push({ method, path: (prefix + layer.route.path).replace(/\/+/g, '/'), guarded });
    } else if (layer.handle && layer.handle.stack) {
      const mount = (layer.regexp.source.match(/^\^\\\/([\w\\/-]+?)\\\/\?\(\?=/) || [, ''])[1].replace(/\\\//g, '/');
      out.push(...walk(layer.handle.stack, `${prefix}/${mount}`));
    }
  }
  return out;
}

const routes = walk(createApp()._router.stack)
  .map((r) => ({ ...r, path: r.path.replace(/\/$/, '') || '/' }))
  .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const group = (p) => (p.split('/')[2] && p.startsWith('/api') ? p.split('/')[2] : p.startsWith('/api') ? 'api' : 'site');
const access = (r) => (r.guarded ? 'login' : 'public');

async function probe(r) {
  // Only requests that cannot change anything: GET anywhere, or any method on a login-protected route (401 comes first).
  const method = r.method === 'ALL' ? 'GET' : r.method;
  if (!r.guarded && method !== 'GET') return { verdict: 'not probed', code: '-' };
  const url = base + r.path.replace(/:[A-Za-z_]+/g, 'x');
  try {
    const res = await fetch(url, { method, signal: AbortSignal.timeout(15000), headers: { accept: 'application/json' } });
    const c = res.status;
    if (c === 404) {
      // Our global handler says "Route not found". Any other 404 is a handler answering "no such record/link".
      const body = await res.text().catch(() => '');
      return /Route not found/.test(body) ? { verdict: 'NOT FOUND (route missing or wrong path)', code: c } : { verdict: 'live (handler said not found)', code: c };
    }
    if (c >= 500) return { verdict: 'SERVER ERROR', code: c };
    if (r.guarded) return c === 401 || c === 403 ? { verdict: 'live (asks for login)', code: c } : { verdict: `UNEXPECTED (expected 401)`, code: c };
    return c < 400 ? { verdict: 'live', code: c } : { verdict: 'live (rejected the empty request)', code: c };
  } catch (e) {
    return { verdict: 'UNREACHABLE', code: e.name === 'TimeoutError' ? 'timeout' : 'no connection' };
  }
}

(async () => {
  const rows = [];
  for (const r of routes) rows.push({ ...r, ...(base ? await probe(r) : {}) });

  const pad = (s, n) => String(s).padEnd(n);
  let lastGroup = '';
  for (const r of rows) {
    const g = group(r.path);
    if (g !== lastGroup) { console.log(`\n[${g}]`); lastGroup = g; }
    console.log(`  ${pad(r.method, 7)}${pad(r.path, 44)}${pad(access(r), 8)}${base ? `${pad(r.code, 13)}${r.verdict}` : ''}`);
  }
  console.log(`\n${rows.length} endpoints: ${rows.filter((r) => r.guarded).length} need login, ${rows.filter((r) => !r.guarded).length} public.`);

  if (base) {
    const count = (f) => rows.filter(f).length;
    const bad = count((r) => /NOT FOUND|SERVER ERROR|UNREACHABLE|UNEXPECTED/.test(r.verdict || ''));
    console.log(`Probe of ${base}: ${count((r) => /^live/.test(r.verdict || ''))} live, ${bad} with problems, ${count((r) => r.verdict === 'not probed')} not probed (public write routes).`);
    if (count((r) => r.verdict === 'UNREACHABLE') === rows.length) console.log('Nothing answered. Is that backend running and is the address right?');
  }

  if (args.includes('--md')) {
    const lines = ['# API endpoints', '', 'Generated by `node scripts/api_status.js --md`. "login" routes need a Clerk session token; "public" routes do not.', ''];
    let g2 = '';
    for (const r of rows) {
      const g = group(r.path);
      if (g !== g2) { lines.push('', `## ${g}`, '', '| Method | Path | Access |', '|---|---|---|'); g2 = g; }
      lines.push(`| ${r.method} | \`${r.path}\` | ${access(r)} |`);
    }
    const out = path.resolve(__dirname, '..', '..', 'docs', 'API.md');
    fs.writeFileSync(out, lines.join('\n') + '\n');
    console.log(`Wrote ${out}`);
  }
  process.exit(0);
})();
